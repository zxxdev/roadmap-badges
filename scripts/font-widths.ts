/**
 * Writes src/badges/font.ts: how wide each character is in DejaVu Sans, read
 * from the font file itself. The badges need it to size their boxes, because
 * there is no browser to measure text in a GitHub Action.
 *
 *   node scripts/font-widths.ts /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf
 *
 * It reads four tables of the TrueType file: "head" (font units per em),
 * "cmap" (character to glyph), "hhea" and "hmtx" (each glyph's advance width,
 * the distance from the start of one glyph to the start of the next). Kerning
 * is left out: badges are short and their text is fitted with textLength.
 *
 * Run `pnpm format` afterwards so the file matches Prettier.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

/** Code points in the table: printable ASCII, Latin-1 and Latin Extended-A. */
const FIRST = 0x20;
const LAST = 0x17f;
const OUTPUT = "src/badges/font.ts";

const argument = process.argv[2];
if (argument === undefined) {
  console.error("usage: node scripts/font-widths.ts <font.ttf>");
  process.exit(2);
}
const path: string = argument;

const font = readFileSync(path);
const tables = readTableDirectory(font);

const unitsPerEm = font.readUInt16BE(table("head") + 18);
const numberOfHMetrics = font.readUInt16BE(table("hhea") + 34);
const hmtx = table("hmtx");
const glyphFor = readCmap(font, table("cmap"));
const family = readName(font, table("name"), 1);
const version = readName(font, table("name"), 5).replace(/^Version\s+/i, "");

const advances: number[] = [];
for (let code = FIRST; code <= LAST; code++) {
  const glyph = glyphFor(code);
  // Glyph 0 is ".notdef", the box drawn for a missing character: not in the font.
  advances.push(glyph === 0 ? 0 : advanceWidth(glyph));
}

const sha256 = createHash("sha256").update(font).digest("hex");
writeFileSync(
  OUTPUT,
  `// Generated by scripts/font-widths.ts from ${family} ${version}.
// Font file sha256: ${sha256}
// Do not edit: run \`pnpm font-widths\` again.

/** The font the widths come from. */
export const FONT = { family: ${JSON.stringify(family)}, version: ${JSON.stringify(version)}, unitsPerEm: ${String(unitsPerEm)} } as const;

/** The first code point in ADVANCES. */
export const FIRST_CODE_POINT = ${String(FIRST)};

/**
 * Advance widths in font units, from U+${hex(FIRST)} to U+${hex(LAST)}. A character's
 * entry is at its code point minus FIRST_CODE_POINT; 0 means the font has no
 * glyph for it (the control characters U+007F to U+009F).
 */
export const ADVANCES: readonly number[] = [${advances.join(", ")}];
`,
);
console.log(`Wrote ${OUTPUT}: ${String(advances.length)} widths from ${family} ${version}.`);

// --- TrueType reading -------------------------------------------------------

/** Where each table starts, by its four-letter tag. */
function readTableDirectory(data: Buffer): Map<string, number> {
  const count = data.readUInt16BE(4);
  const found = new Map<string, number>();
  for (let i = 0; i < count; i++) {
    const record = 12 + i * 16;
    found.set(data.toString("latin1", record, record + 4), data.readUInt32BE(record + 8));
  }
  return found;
}

function table(tag: string): number {
  const offset = tables.get(tag);
  if (offset === undefined) throw new Error(`${path} has no "${tag}" table`);
  return offset;
}

/** Glyphs after the last full metric share its advance width (monospaced tails). */
function advanceWidth(glyph: number): number {
  const index = Math.min(glyph, numberOfHMetrics - 1);
  return font.readUInt16BE(hmtx + index * 4);
}

/**
 * The character-to-glyph lookup, from the Windows Unicode BMP subtable
 * (platform 3, encoding 1), which is format 4: ranges of code points
 * ("segments"), each mapped by an offset or through an array of glyph ids.
 */
function readCmap(data: Buffer, cmap: number): (code: number) => number {
  const count = data.readUInt16BE(cmap + 2);
  let subtable: number | undefined;
  for (let i = 0; i < count; i++) {
    const record = cmap + 4 + i * 8;
    if (data.readUInt16BE(record) === 3 && data.readUInt16BE(record + 2) === 1) {
      subtable = cmap + data.readUInt32BE(record + 4);
    }
  }
  if (subtable === undefined || data.readUInt16BE(subtable) !== 4) {
    throw new Error(`${path} has no format 4 Unicode cmap`);
  }

  const segments = data.readUInt16BE(subtable + 6) / 2;
  const endCodes = subtable + 14;
  const startCodes = endCodes + segments * 2 + 2; // after a reserved uint16
  const deltas = startCodes + segments * 2;
  const rangeOffsets = deltas + segments * 2;

  return (code) => {
    for (let s = 0; s < segments; s++) {
      if (code > data.readUInt16BE(endCodes + s * 2)) continue;
      const start = data.readUInt16BE(startCodes + s * 2);
      if (code < start) return 0;
      const delta = data.readInt16BE(deltas + s * 2);
      const rangeOffset = data.readUInt16BE(rangeOffsets + s * 2);
      if (rangeOffset === 0) return (code + delta) & 0xffff;
      // The offset is in bytes from where it is stored, into the glyph id array.
      const at = rangeOffsets + s * 2 + rangeOffset + (code - start) * 2;
      const glyph = data.readUInt16BE(at);
      return glyph === 0 ? 0 : (glyph + delta) & 0xffff;
    }
    return 0;
  };
}

/** A string from the "name" table, in its Windows (UTF-16BE) form. */
function readName(data: Buffer, name: number, nameId: number): string {
  const count = data.readUInt16BE(name + 2);
  const strings = name + data.readUInt16BE(name + 4);
  for (let i = 0; i < count; i++) {
    const record = name + 6 + i * 12;
    if (data.readUInt16BE(record) !== 3 || data.readUInt16BE(record + 6) !== nameId) continue;
    const length = data.readUInt16BE(record + 8);
    const start = strings + data.readUInt16BE(record + 10);
    return Buffer.from(data.subarray(start, start + length))
      .swap16()
      .toString("utf16le");
  }
  throw new Error(`${path} has no name ${String(nameId)}`);
}

function hex(code: number): string {
  return code.toString(16).toUpperCase().padStart(4, "0");
}
